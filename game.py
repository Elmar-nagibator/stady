import os
import sys
import time
import random

# ==========================================
# 1. СИСТЕМНЫЕ ФУНКЦИИ И ОФОРМЛЕНИЕ
# ==========================================

def print_slow(text, delay=0.02):
    """Побуквенный вывод текста для создания атмосферы хоррора"""
    for char in text:
        sys.stdout.write(char)
        sys.stdout.flush()
        time.sleep(delay)
    print()

def clear_screen():
    """Очистка консоли"""
    os.system('cls' if os.name == 'nt' else 'clear')

# Состояние игрока
player = {
    "hp": 100,
    "sanity": 100,
    "stamina": 100,
    "inventory": ["Бутылка воды"]
}

def show_status():
    """Вывод шапки со статусом персонажа"""
    print("=" * 55)
    print(f"❤️  HP: {player['hp']}/100  | 🧠  Рассудок: {player['sanity']}/100  | ⚡  Выносливость: {player['stamina']}/100")
    print(f"🎒 Инвентарь: {', '.join(player['inventory']) if player['inventory'] else 'Пусто'}")
    print("=" * 55)

def apply_damage(hp=0, sanity=0, stamina=0):
    """Изменение параметров и проверка условий поражения"""
    player['hp'] -= hp
    player['sanity'] -= sanity
    player['stamina'] -= stamina
    
    # Ограничения по максимуму/минимуму
    player['stamina'] = max(0, min(100, player['stamina']))
    
    if player['hp'] <= 0:
        print_slow("\n💀 Ваши силы иссякли... Вы пали жертвой Закулисья.")
        sys.exit()
    if player['sanity'] <= 0:
        print_slow("\n🤪 Разум окончательно покинул вас. Вы стали бессмысленной тенью эти стен...")
        sys.exit()

# ==========================================
# 2. ПРОЛОГ
