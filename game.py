def handle_footsteps():
    """Обработка события №2 (Шаги вдали)"""
    clear_screen()
    show_status()
    print_slow("\n[!] Вы слышите шаги... вам становится не по себе. Бежать? Или это такой же путник?")
    print("1. Пойти к звуку")
    print("2. Спрятаться за углом")
    print("3. Уйти подальше")
    
    choice = input("\nВаш выбор (1-3): ").strip()
    
    if choice == "1":
        clear_screen()
        show_status()
        print_slow("\nВам тяжело идти, вы устали блуждать в одиночестве. Вы готовы идти к неизвестности...")
        print("1. Наконец-то дойти")
        print("2. БеЖаТь")
        sub_choice = input("\nВаш выбор (1-2): ").strip()
        
        if sub_choice == "1":
            clear_screen()
            print_slow("\n💀 Черт. Вы видите... это... ужасающий монстр с длинными когтями!")
            print_slow("Страх берет верх, ноги не слушаются, он бежит прямо на вас...")
            print_slow("И больше вы ничего не помните.")
            apply_damage(hp=100)
        else:
            print_slow("\n🏃 Чутье кричит бежать! Это явно не что-то хорошее.")
            print_slow("Вы сваливаете оттуда. И снова этот раздражающий шум ламп...")
            apply_damage(stamina=20, sanity=10)
            
    elif choice == "2":
        print_slow("\n🙈 Вы спрятались. Со временем шаги стихли. Бояться нечего, пора продолжать путь.")
        apply_damage(sanity=5)
    else:
        print_slow("\n🚶 Вы ушли от греха подальше. Здравый смысл подсказывает, что вы поступили правильно.")
        apply_damage(stamina=10)

def level_1():
    while True:
        clear_screen()
        show_status()
        print("\n--- УРОВЕНЬ 1: ЖЕЛТЫЕ КОРИДОРЫ ---")
        print("1. Пойти вперёд")
        print("2. Пойти вправо")
        print("3. Пойти влево")
        print("4. Пойти назад")
        
        move = input("\nКуда направиться? (1-4): ").strip()
        if move not in ["1", "2", "3", "4"]:
            continue

        # Генерация события (1: 30%, 2: 40%, 3: 20%, 4: 10%)
        event = random.choices([1, 2, 3, 4], weights=[0.30, 0.40, 0.20, 0.10])[0]
        
        if event == 1:
            print_slow("\n💡 Вы раздражены гулом ламп, а обои будто въедаются в сознание...")
            apply_damage(sanity=5)
            input("\nНажмите Enter, чтобы продолжить...")
            
        elif event == 2:
            handle_footsteps()
            input("\nНажмите Enter, чтобы продолжить...")
            
        elif event == 3:
            print_slow("\n⏳ Вам начинает казаться, что выхода нет... Сколько можно идти?")
            print_slow("Вы окончательно сбились со счета времени.")
            apply_damage(sanity=10)
            input("\nНажмите Enter, чтобы продолжить...")
            
        elif event == 4:
            clear_screen()
            print_slow("\n🔴 НЕУЖЕЛИ?! Вы заметили то, что сильно выделяется...")
            print_slow("ЭТО ДВЕРЬ! Яркая красная дверь!")
            print_slow("Вы бежите изо всех сил, надеясь на свободу...")
            input("\nНажмите Enter, чтобы открыть дверь...")
            break

# ==========================================
# 4. ГЛАВНЫЙ ЗАПУСК
# ==========================================

def main():
    play_intro()
    level_1()
    
    # Переход на следующий уровень
    clear_screen()
    print_slow("🎉 ВЫ ПРОШЛИ УРОВЕНЬ 1!")
    print_slow("Но Закулисье так просто не отпускает...")
    print_slow("\n[Далее следует Уровень 2: Затопленная парковка...]")

if __name__ == "__main__":
    main()